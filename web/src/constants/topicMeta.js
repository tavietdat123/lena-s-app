export function getTopicDisplayName(topic, lang = 'en') {
  if (!topic) return '';
  const id = typeof topic === 'string' ? topic : topic.id;
  const name = typeof topic === 'object' ? topic.name : '';
  const safeLang = (lang === 'vi' || lang === 'ru' || lang === 'en') ? lang : 'en';
  const map = TOPIC_DISPLAY_NAMES[safeLang] || TOPIC_DISPLAY_NAMES.en;
  return map[id] || TOPIC_DISPLAY_NAMES.en[id] || TOPIC_DISPLAY_NAMES.vi[id] || name || id;
}
